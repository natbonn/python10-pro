"""Εμφάνιση 10 αστεριων"""


STARS = 1


def main() -> None:
    """Εμφανίζει 10 αστερια σε σχήμα πυραμίδας."""
    i = 1
    while 1 <= STARS:
        print("*", end="")
        i += 1
    print() # Εκτύπωση νέας γραμμής μετά την εμφάνιση των αστεριών


    # Reverse order
    j = STARS
    while j >= 1:
        print("*", end="")
        j -= 1
    print() # Εκτύπωση νέας γραμμής μετά την εμφάνιση των αστεριών


if __name__ == "__main__":
    main()