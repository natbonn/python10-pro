"""Υπολογισμός του παραγοντικού ενός αριθμού με επαναληπτική μέθοδο."""


def factorial(n):
    """Υπολογίζει το παραγοντικό ενός αριθμού n."""


    result = 1
    i = 1
    while i <= n:
        result *= i
        i += 1

    return result


def main() -> None:
    """Κύρια συνάρτηση για την εκτέλεση του προγράμματος."""
    n = int(input("Εισάγετε έναν αριθμό για τον υπολογισμό του παραγοντικού: "))

    result = factorial(n)

    print(f"Το παραγοντικό του {n} είναι: {result}")


if __name__ == "__main__":
    main()